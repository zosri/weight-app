// Μετά από τόσα skip σερί σε μια ερώτηση, σταματάμε να τη ρωτάμε.
export const MAX_SKIPS = 20

/** Οι ερωτήσεις που όντως τίθενται, με τα σερί παραλείψεων υπολογισμένα. */
export function activeQuestions(streaks = {}) {
  return QUESTIONS.filter((q) => q.active !== false && (streaks[q.id] || 0) < MAX_SKIPS)
}

/**
 * Εμφάνιση αριθμητικής τιμής. Το 'clock' δέχεται και τιμές πάνω από 24:
 * 25.5 σημαίνει 01:30 τα ξημερώματα της επόμενης — έτσι ο αριθμός μένει
 * μονότονος και η διάμεσος βγαίνει σωστά.
 */
export function formatAnswer(q, v) {
  if (v === 'skip' || v === undefined || v === null) return '—'
  const n = Number(v)
  if (!Number.isFinite(n)) return '—'
  if (q.kind === 'clock') {
    const h = Math.floor(n % 24)
    const m = Math.round((n % 1) * 60)
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}${n >= 24 ? '+' : ''}`
  }
  if (q.kind === 'hours') return `${n % 1 === 0 ? n : n.toFixed(1)} ώ.`
  return String(n)
}
